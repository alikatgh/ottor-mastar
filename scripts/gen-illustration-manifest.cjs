/**
 * Generates src/data/available-illustrations.ts from the optimized plate files
 * that actually exist in public/plants/full/.
 *
 * The app uses this manifest to decide which plants show a botanical plate, so
 * you never have to touch the data by hand: add a new `plant-NN-ill` source,
 * run `npm run optimize`, and the plate lights up automatically. Built to catch
 * the "6 plants have no real plate" gap — a plant is illustrated iff its file
 * is present here.
 */
const fs = require('fs');
const path = require('path');

const FULL_DIR = path.join(__dirname, '../public/plants/full');
const OUT = path.join(__dirname, '../src/data/available-illustrations.ts');

const slugs = fs
  .readdirSync(FULL_DIR)
  .filter((f) => f.endsWith('-ill.webp'))
  .map((f) => f.replace('.webp', ''))
  .sort();

const content =
  `// AUTO-GENERATED by scripts/gen-illustration-manifest.cjs — do not edit by hand.\n` +
  `// Botanical-plate slugs that have optimized image files in public/plants/.\n` +
  `// Regenerate with: node scripts/gen-illustration-manifest.cjs (or npm run optimize).\n` +
  `export const AVAILABLE_ILLUSTRATIONS: string[] = ${JSON.stringify(slugs, null, 2)};\n`;

fs.writeFileSync(OUT, content);
console.log(`Wrote ${slugs.length} illustration slugs to ${path.relative(process.cwd(), OUT)}`);
